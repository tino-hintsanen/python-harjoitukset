hytti = input("mikä hyttiluokka sinulla on? (lux, a, b ,c") 

if hytti == "lux":
    print("parvekkeellinen hytti ylakannella ")
elif hytti == "a":
    print("ikkunallinen hytti autokannen ylapuolella ")
elif hytti == "b":
    print("ikkunaton hytti autokannen ylapuolella ")
elif hytti == "c":
    print("ikkunaton hytti autokannen alapuolella ")
else:
    print("virheellinen hyttiluokka")
                            

